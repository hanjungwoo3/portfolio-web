// 베이시스(선물 − 현물) 설명 툴팁 — 선물 패널·시장 카드가 같이 쓴다(사용자 2026-11-13 "베이시스 툴팁에 설명 넣어줘")
export function basisHint(b: number | null | undefined): string {
  const now = b == null ? "" : b < 0
    ? `지금 ${b.toFixed(2)} = 선물이 현물보다 ${Math.abs(b).toFixed(2)}p 싸다 → 선물 쪽 매도 우위(살짝 비관). 마이너스가 깊어지면 차익거래가 현물을 팔아 지수에 매도 압력.`
    : `지금 +${b.toFixed(2)} = 선물이 현물보다 ${b.toFixed(2)}p 비싸다 → 정상(이자 비용만큼 선물이 비싼 게 보통). 크게 벌어지면 차익거래가 현물을 사 지수에 매수 압력.`;
  return `베이시스 = 코스피200 선물 가격 − 코스피200 지수(현물).\n${now}\n한 번 찍힌 값보다 방향(플러스로 돌아서는지·더 깊어지는지)을 보세요. 만기일이 가까울수록 0에 붙습니다.`;
}
